"""Evidence - the files an audit project is based on, and the passages stored from them.

Why the passage browser is the important half of this page
----------------------------------------------------------
A citation in this system points at an ``EvidenceChunk`` - shown to the auditor as a
*passage*: an id, a locator, and the exact text the validator matched a quotation
against. When an auditor checks whether the model quoted the evidence faithfully, *this*
is the ground truth they are checking against - not the original PDF, which the pipeline
never re-reads after ingestion. So the passage browser is not a debugging view. It is
the working paper: it shows every stored passage with its locator, lets the auditor
search inside them, and lets them jump straight to a passage id copied from a citation,
including one that belongs to a different file in the audit project.

What the upload panel reports
-----------------------------
Ingestion can partly fail: a file may store but not parse, parse but produce no passage,
or parse with warnings from the extractor. ``ingest_file`` records all of those on the
row rather than raising, so the upload result here prints one plain line per file with
the passage, page and row counts, and collects every warning in one place. A file that
produced no passage is invisible to retrieval no matter how relevant it looks in the
list, and the auditor needs to be told so at the moment they upload it.

Deleting evidence is an audit-relevant act
------------------------------------------
Deleting a file removes its passages. Citations that pointed at those passages survive
with an unresolved id - the same signal a fabricated citation produces - so the
confirmation says exactly that before the button is enabled.

Why provenance is shouted rather than mentioned
-----------------------------------------------
This repository contains material that reads exactly like organisational evidence and is
not: generated datasets, and historical case studies reconstructed from publicly
documented failure patterns under invented organisation names. Realism is the point of
those files and it is also the risk, because a realistic account listing quoted out of
context becomes a claim about a real company. So provenance is not a discreet metadata
field on this page. It is a column on every row, a banner over the list whenever anything
non-synthetic is present, a full-width banner on the detail view, and a required choice at
upload. ``EvidenceType`` says what an artefact *is*; ``EvidenceProvenance`` says where it
*came from*, and only the second one determines what may be claimed on the strength of it.
"""

